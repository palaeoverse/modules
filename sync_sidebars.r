#!/usr/bin/env Rscript

# Write _sidebars.yml: one sidebar for every module that has a _sidebar.yml.
#
# A module's _sidebar.yml lists its pages in the format of Quarto's sidebar
# `contents`, with paths relative to the module directory, e.g.
#
#   - index.qmd
#   - exercise1.qmd
#   - section: Appendix
#     href: appendix/index.qmd
#     contents:
#       - appendix/exercise1.qmd
#
# Quarto only reads sidebar definitions from the project config, so _quarto.yml
# pulls this file in with `metadata-files: [_sidebars.yml]`. Register this as
# `pre-render` so it runs before every render.
#
# Usage: Rscript sync_sidebars.r [modules_dir]   (run from the project root)
#   modules_dir: where the module directories live, relative to the project
#                root (default "."; "training/modules" on the website)

library(yaml)

args        <- commandArgs(trailingOnly = TRUE)
modules_dir <- if (length(args) > 0) args[[1]] else "."
out         <- "_sidebars.yml"

# make the local paths of a sidebar item relative to the project root
prefix <- function(item, dir) {
  add_dir <- function(p) if (grepl("://", p)) p else file.path(dir, p)
  if (is.character(item)) return(add_dir(item))
  if (!is.null(item$href)) item$href <- add_dir(item$href)
  if (!is.null(item$contents)) item$contents <- lapply(item$contents, prefix, dir)
  item
}

sidebars <- lapply(Sys.glob(file.path(modules_dir, "*", "_sidebar.yml")), function(f) {
  dir <- sub("^[.]/", "", dirname(f))
  list(
    id        = gsub("/", "-", dir),
    style     = "floating",
    alignment = "left",
    collapse-level = 1,
    contents  = lapply(read_yaml(f), prefix, dir)
  )
})

content <- c(
  paste0("# ", out, " -- AUTOGENERATED by sync_sidebars.r, DO NOT EDIT."),
  if (length(sidebars) == 0) "website: {}" else
    strsplit(as.yaml(list(website = list(sidebar = sidebars))), "\n")[[1]]
)

# only rewrite when changed, so preview doesn't loop on a file-change reload
if (!file.exists(out) || !identical(readLines(out, warn = FALSE), content)) {
  writeLines(content, out)
  message("sync_sidebars: wrote ", out, " (", length(sidebars), " sidebar(s))")
}
